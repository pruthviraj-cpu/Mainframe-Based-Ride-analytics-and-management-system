def parse_ledger_record(line: str) -> dict:
    """
    Parses a single 80-byte line from FILE3_MASTER_LEDGER.ps
    Layout:
      Col 01-08: Trip ID
      Col 09-16: Driver ID
      Col 17-28: Timestamp (YYYYMMDDHHMM)
      Col 29-31: Pickup Zone ID
      Col 32-34: Dropoff Zone ID
      Col 35-40: Distance (PIC 9(4)V99)
      Col 41-46: Total Fare (PIC 9(4)V99)
      Col 47-52: Driver Payout (PIC 9(4)V99)
      Col 53-58: Platform Commission (PIC 9(4)V99)
      Col 59-63: Duration in minutes (PIC 9(3)V99)
      Col 64-68: Implied Speed MPH (PIC 9(3)V99)
      Col 69-80: Blank Padding
    """
    rec = line.rstrip("\r\n").ljust(80, " ")
    trip_id = rec[0:8].strip()
    driver_id = rec[8:16].strip()
    ts_raw = rec[16:28].strip()

    # Format timestamp nicely: YYYY-MM-DD HH:MM
    if len(ts_raw) == 12:
        formatted_ts = f"{ts_raw[0:4]}-{ts_raw[4:6]}-{ts_raw[6:8]} {ts_raw[8:10]}:{ts_raw[10:12]}"
    else:
        formatted_ts = ts_raw

    p_zone = rec[28:31].strip()
    d_zone = rec[31:34].strip()

    try:
        dist = float(rec[34:40].strip()) / 100.0
    except (ValueError, IndexError):
        dist = 0.0

    try:
        fare = float(rec[40:46].strip()) / 100.0
    except (ValueError, IndexError):
        fare = 0.0

    try:
        driver_payout = float(rec[46:52].strip()) / 100.0
    except (ValueError, IndexError):
        driver_payout = round(fare * 0.75, 2)

    try:
        platform_comm = float(rec[52:58].strip()) / 100.0
    except (ValueError, IndexError):
        platform_comm = round(fare * 0.25, 2)

    try:
        dur = float(rec[58:63].strip()) / 100.0
    except (ValueError, IndexError):
        dur = 0.0

    try:
        speed = float(rec[63:68].strip()) / 100.0
    except (ValueError, IndexError):
        speed = 0.0

    return {
        "trip_id": trip_id,
        "driver_id": driver_id,
        "timestamp": formatted_ts,
        "raw_timestamp": ts_raw,
        "pickup_zone_id": p_zone,
        "dropoff_zone_id": d_zone,
        "pickup_zone": ZONE_NAMES.get(p_zone, f"Zone {p_zone}"),
        "dropoff_zone": ZONE_NAMES.get(d_zone, f"Zone {d_zone}"),
        "distance_miles": round(dist, 2),
        "fare_usd": round(fare, 2),
        "driver_payout_usd": round(driver_payout, 2),
        "platform_commission_usd": round(platform_comm, 2),
        "duration_mins": int(round(dur)),
        "speed_mph": round(speed, 2),
        "status": "COMPLETED",
        "raw_record": rec,
    }


def parse_fraud_record(line: str) -> dict:
    """
    Parses a single 80-byte line from FILE4_FRAUD_REPORT.ps
    """
    rec = line.rstrip("\r\n").ljust(80, " ")
    trip_id = rec[0:8].strip()
    driver_id = rec[8:16].strip()
    reason = rec[16:28].strip()

    try:
        dist = float(rec[28:34].strip()) / 100.0
    except (ValueError, IndexError):
        dist = 0.0

    try:
        fare = float(rec[34:40].strip()) / 100.0
    except (ValueError, IndexError):
        fare = 0.0

    try:
        dur = float(rec[40:45].strip()) / 100.0
    except (ValueError, IndexError):
        dur = 0.0

    try:
        speed = float(rec[45:50].strip()) / 100.0
    except (ValueError, IndexError):
        speed = 0.0

    return {
        "trip_id": trip_id,
        "driver_id": driver_id,
        "driver_name": f"Driver {driver_id}",
        "timestamp": "Batch Audit Entry",
        "raw_timestamp": "",
        "pickup_zone_id": "000",
        "dropoff_zone_id": "000",
        "pickup_zone": "Quarantined (Audit)",
        "dropoff_zone": "Quarantined (Audit)",
        "fraud_reason": reason,
        "distance_miles": round(dist, 2),
        "fare_usd": round(fare, 2),
        "driver_payout_usd": 0.00,
        "platform_commission_usd": 0.00,
        "duration_mins": int(round(dur)),
        "speed_mph": round(speed, 2),
        "implied_speed_mph": round(speed, 2),
        "status": f"FRAUD: {reason.strip()}",
        "is_fraud": True,
        "raw_record": rec,
    }


class MainframeDataStore:
    """Direct file-based reader & query provider for mainframe output datasets."""

    @staticmethod
    def get_ledger_trips(search=None, zone_id=None, include_fraud=True):
        if not os.path.exists(FILE3_LEDGER):
            return []

        trips = []
        with open(FILE3_LEDGER, "r", encoding="utf-8") as f:
            for line in f:
                if len(line.strip()) == 0:
                    continue
                trip = parse_ledger_record(line)

                if search:
                    q = search.lower()
                    if (
                        q not in trip["trip_id"].lower()
                        and q not in trip["driver_id"].lower()
                        and q not in trip["pickup_zone"].lower()
                        and q not in trip["dropoff_zone"].lower()
                    ):
                        continue

                if zone_id and zone_id != "ALL":
                    if trip["pickup_zone_id"] != zone_id and trip["dropoff_zone_id"] != zone_id:
                        continue

                trips.append(trip)

        if include_fraud and os.path.exists(FILE4_FRAUD):
            with open(FILE4_FRAUD, "r", encoding="utf-8") as f:
                for line in f:
                    if len(line.strip()) == 0:
                        continue
                    fraud_trip = parse_fraud_record(line)
                    if search:
                        q = search.lower()
                        if (
                            q not in fraud_trip["trip_id"].lower()
                            and q not in fraud_trip["driver_id"].lower()
                            and q not in fraud_trip["status"].lower()
                        ):
                            continue
                    trips.append(fraud_trip)

        return trips

    @staticmethod
    def get_fraud_trips():
        if not os.path.exists(FILE4_FRAUD):
            return []

        frauds = []
        with open(FILE4_FRAUD, "r", encoding="utf-8") as f:
            for line in f:
                if len(line.strip()) == 0:
                    continue
                frauds.append(parse_fraud_record(line))
        return frauds

    @staticmethod
    def get_summary_metrics():
        trips = MainframeDataStore.get_ledger_trips()
        frauds = MainframeDataStore.get_fraud_trips()

        total_trips = len(trips)
        total_revenue = sum(t["fare_usd"] for t in trips)
        total_payout = sum(t["driver_payout_usd"] for t in trips)
        total_platform = sum(t["platform_commission_usd"] for t in trips)
        unique_drivers = set(t["driver_id"] for t in trips)

        avg_duration = sum(t["duration_mins"] for t in trips) / total_trips if total_trips > 0 else 0.0
        avg_distance = sum(t["distance_miles"] for t in trips) / total_trips if total_trips > 0 else 0.0
        avg_fare = total_revenue / total_trips if total_trips > 0 else 0.0

        # Raw file counts
        raw_f1_count = 0
        if os.path.exists(FILE1_RAW):
            with open(FILE1_RAW, "r", encoding="utf-8") as f:
                raw_f1_count = sum(1 for line in f if len(line.strip()) > 0)

        raw_f2_count = 0
        if os.path.exists(FILE2_RAW):
            with open(FILE2_RAW, "r", encoding="utf-8") as f:
                raw_f2_count = sum(1 for line in f if len(line.strip()) > 0)

        sorted_f1_count = 0
        if os.path.exists(FILE1_SORTED):
            with open(FILE1_SORTED, "r", encoding="utf-8") as f:
                sorted_f1_count = sum(1 for line in f if len(line.strip()) > 0)

        duplicates_purged = max(0, raw_f1_count - sorted_f1_count)

        return {
            "totalTrips": total_trips,
            "totalRevenue": round(total_revenue, 2),
            "driverPayouts": round(total_payout, 2),
            "platformCommission": round(total_platform, 2),
            "activeDrivers": len(unique_drivers),
            "avgTripDurationMins": round(avg_duration, 1),
            "avgTripDistanceMiles": round(avg_distance, 2),
            "avgFareUSD": round(avg_fare, 2),
            "fraudTripsCount": len(frauds),
            "batchId": "JOB_RIDE_PROD_001",
            "mainframeReturnCode": "RC=0000",
            "rawFile1Records": raw_f1_count,
            "rawFile2Records": raw_f2_count,
            "duplicatesRemoved": duplicates_purged,
            "cleanMergedRecords": total_trips,
            "lastBatchTimestamp": datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC"),
            "executionEnvironment": "IBM z/OS v2.5 / COBOL RIDEANLZ",
        }

    @staticmethod
    def get_drivers():
        trips = MainframeDataStore.get_ledger_trips()
        drivers_map = {}

        for t in trips:
            did = t["driver_id"]
            if did not in drivers_map:
                drivers_map[did] = {
                    "driver_id": did,
                    "name": f"Driver {did}",
                    "status": "ON_DUTY",
                    "trips_completed": 0,
                    "total_revenue": 0.0,
                    "total_duration": 0,
                    "rating": 4.90,
                    "vehicle": "Sedan / Hybrid Fleet",
                }

            drivers_map[did]["trips_completed"] += 1
            drivers_map[did]["total_revenue"] += t["fare_usd"]
            drivers_map[did]["total_duration"] += t["duration_mins"]

        driver_list = []
        for did, d in drivers_map.items():
            avg_dur = d["total_duration"] / d["trips_completed"] if d["trips_completed"] > 0 else 0
            d["avg_trip_mins"] = round(avg_dur, 1)
            d["total_revenue"] = round(d["total_revenue"], 2)
            driver_list.append(d)

        # Sort by total trips completed descending
        driver_list.sort(key=lambda x: x["trips_completed"], reverse=True)
        return driver_list

    @staticmethod
    def get_hourly_analytics():
        trips = MainframeDataStore.get_ledger_trips()
        hourly_map = {f"{h:02d}:00": {"trips": 0, "revenue": 0.0} for h in range(0, 24, 2)}

        for t in trips:
            ts = t["raw_timestamp"]
            if len(ts) >= 10:
                hour = int(ts[8:10])
                bucket_h = (hour // 2) * 2
                bucket_key = f"{bucket_h:02d}:00"
                if bucket_key in hourly_map:
                    hourly_map[bucket_key]["trips"] += 1
                    hourly_map[bucket_key]["revenue"] += t["fare_usd"]

        result = []
        for k in sorted(hourly_map.keys()):
            result.append({
                "hour": k,
                "trips": hourly_map[k]["trips"],
                "revenue": round(hourly_map[k]["revenue"], 0),
            })
        return result

    @staticmethod
    def get_zone_analytics():
        trips = MainframeDataStore.get_ledger_trips()
        zones_map = {}

        for t in trips:
            pz = t["pickup_zone_id"]
            if pz not in zones_map:
                zones_map[pz] = {
                    "zone_id": pz,
                    "name": ZONE_NAMES.get(pz, f"Zone {pz}"),
                    "pickups": 0,
                    "dropoffs": 0,
                    "total_fare": 0.0,
                }
            zones_map[pz]["pickups"] += 1
            zones_map[pz]["total_fare"] += t["fare_usd"]

            dz = t["dropoff_zone_id"]
            if dz not in zones_map:
                zones_map[dz] = {
                    "zone_id": dz,
                    "name": ZONE_NAMES.get(dz, f"Zone {dz}"),
                    "pickups": 0,
                    "dropoffs": 0,
                    "total_fare": 0.0,
                }
            zones_map[dz]["dropoffs"] += 1

        result = []
        for zid, z in zones_map.items():
            avg_fare = z["total_fare"] / z["pickups"] if z["pickups"] > 0 else 0.0
            z["avg_fare"] = round(avg_fare, 2)
            result.append(z)

        result.sort(key=lambda x: x["pickups"], reverse=True)
        return result[:10]
